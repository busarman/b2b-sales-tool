alter table public.inventory add column if not exists price_source_file text, add column if not exists price_synced_at timestamptz;
alter table public.cnhi_spot add column if not exists price_source_file text, add column if not exists price_synced_at timestamptz;

create table if not exists public.equipment_price_sync_runs (
  id bigint generated by default as identity primary key,
  source_file text not null,
  inventory_count integer not null,
  spot_count integer not null,
  created_at timestamptz not null default now()
);
alter table public.equipment_price_sync_runs enable row level security;
revoke all on public.equipment_price_sync_runs from anon, authenticated;

create or replace function public.apply_equipment_price_sync(p_inventory jsonb, p_spot jsonb, p_source_file text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare inventory_count integer; spot_count integer; synced_at timestamptz := now();
begin
  if p_source_file is null or p_source_file !~ '^PQ PL for dealers_[0-9]{8}\.xlsx$' then
    raise exception 'Invalid price filename';
  end if;
  if jsonb_typeof(p_inventory) is distinct from 'array' or jsonb_typeof(p_spot) is distinct from 'array' then
    raise exception 'Expected price arrays';
  end if;
  if jsonb_array_length(p_inventory) = 0 or jsonb_array_length(p_spot) = 0 then raise exception 'Empty prices'; end if;
  if exists(select 1 from jsonb_array_elements(p_inventory || p_spot) x
    where nullif(x->>'external_id','') is null or nullif(x->>'model','') is null
      or x->>'contract_currency' is null or (x->>'contract_currency') !~ '^[A-Z]{3}$'
      or x->>'price_with_vat' is null or (x->>'price_with_vat')::numeric < 0) then
    raise exception 'Invalid price record';
  end if;
  if exists(select 1 from jsonb_array_elements(p_inventory) x group by x->>'external_id' having count(*) > 1)
    or exists(select 1 from jsonb_array_elements(p_spot) x group by x->>'external_id' having count(*) > 1) then
    raise exception 'Duplicate price ID';
  end if;
  -- Serialize price imports and lock active records against concurrent stock updates.
  perform pg_advisory_xact_lock(611111410);
  if exists(select 1 from public.equipment_price_sync_runs where source_file > p_source_file) then
    raise exception 'A newer price file has already been imported';
  end if;
  perform 1 from public.inventory where is_active for update;
  perform 1 from public.cnhi_spot where is_active for update;
  if exists(select 1 from public.inventory i where i.is_active and not exists(
    select 1 from jsonb_array_elements(p_inventory) x where x->>'external_id'=i.external_id
      and x->>'serial_number'=i.serial_number and x->>'model'=i.model))
    or exists(select 1 from public.cnhi_spot i where i.is_active and not exists(
    select 1 from jsonb_array_elements(p_spot) x where x->>'external_id'=i.external_id and x->>'model'=i.model)) then
    raise exception 'Price file does not cover the current active stock';
  end if;
  update public.inventory i set price_with_vat=x.price_with_vat, contract_currency=x.contract_currency,
    price_source_file=p_source_file, price_synced_at=synced_at
  from jsonb_to_recordset(p_inventory) as x(external_id text, model text, serial_number text, price_with_vat numeric, contract_currency text)
  where i.is_active and i.external_id=x.external_id and i.serial_number=x.serial_number and i.model=x.model;
  get diagnostics inventory_count = row_count;
  update public.cnhi_spot i set price_with_vat=x.price_with_vat, contract_currency=x.contract_currency,
    price_source_file=p_source_file, price_synced_at=synced_at
  from jsonb_to_recordset(p_spot) as x(external_id text, model text, price_with_vat numeric, contract_currency text)
  where i.is_active and i.external_id=x.external_id and i.model=x.model;
  get diagnostics spot_count = row_count;
  insert into public.equipment_price_sync_runs(source_file,inventory_count,spot_count) values(p_source_file,inventory_count,spot_count);
  return jsonb_build_object('inventory_count',inventory_count,'spot_count',spot_count,'synced_at',synced_at);
end;
$$;
revoke all on function public.apply_equipment_price_sync(jsonb,jsonb,text) from public, anon, authenticated;
grant execute on function public.apply_equipment_price_sync(jsonb,jsonb,text) to service_role;
